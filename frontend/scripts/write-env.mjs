// Writes the SPA's deployment settings into an Angular environment file from environment
// variables, so a deployment is configured in its host (Vercel project env vars) rather than in
// code. Angular compiles environment files in at build time; this runs just before `ng build`.
//
//   HVAC_API_URL                   API base, e.g. https://api.example.com/api      (required)
//   HVAC_SUPABASE_URL              https://<project>.supabase.co                     (required)
//   HVAC_SUPABASE_PUBLISHABLE_KEY  Supabase publishable (anon) key — public by design (required)
//   HVAC_SENTRY_DSN                optional; empty keeps Sentry out of the bundle
//   HVAC_DEFAULT_LANGUAGE          optional; UI language for users who have not picked one: en (default) or it
//
// Usage: node scripts/write-env.mjs [--dev]
//   (default) writes src/environments/environment.ts             (production build)
//   --dev     writes src/environments/environment.development.ts (ng serve; API defaults to localhost)
//
// With none of the variables set it leaves the committed file alone, so a plain local build still
// works. On Vercel (VERCEL=1) or with HVAC_REQUIRE_ENV=1 a missing required variable fails the
// build instead of shipping placeholder settings.

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dev = process.argv.includes('--dev');
const env = process.env;
const strict = env.VERCEL === '1' || env.HVAC_REQUIRE_ENV === '1';

const settings = {
  apiUrl: env.HVAC_API_URL ?? (dev ? 'http://localhost:5299/api' : undefined),
  supabaseUrl: env.HVAC_SUPABASE_URL,
  publishableKey: env.HVAC_SUPABASE_PUBLISHABLE_KEY,
  sentryDsn: env.HVAC_SENTRY_DSN ?? '',
  defaultLanguage: env.HVAC_DEFAULT_LANGUAGE || 'en',
};

const configured = ['HVAC_API_URL', 'HVAC_SUPABASE_URL', 'HVAC_SUPABASE_PUBLISHABLE_KEY'].filter((k) => env[k]);
const missing = Object.entries({
  HVAC_API_URL: settings.apiUrl,
  HVAC_SUPABASE_URL: settings.supabaseUrl,
  HVAC_SUPABASE_PUBLISHABLE_KEY: settings.publishableKey,
})
  .filter(([, value]) => !value)
  .map(([key]) => key);

const file = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'environments', dev ? 'environment.development.ts' : 'environment.ts');

if (configured.length === 0 && !strict) {
  console.log(`write-env: no HVAC_* variables set — keeping ${file}`);
  process.exit(0);
}
if (!['en', 'it'].includes(settings.defaultLanguage)) {
  console.error(`write-env: HVAC_DEFAULT_LANGUAGE must be en or it, got '${settings.defaultLanguage}'.`);
  process.exit(1);
}
if (missing.length > 0) {
  console.error(`write-env: missing ${missing.join(', ')} — set them in the deployment's environment variables.`);
  process.exit(1);
}

const q = (value) => JSON.stringify(value);
writeFileSync(
  file,
  `// Generated by scripts/write-env.mjs from HVAC_* environment variables — do not commit.
export const environment = {
  production: ${!dev},
  apiUrl: ${q(settings.apiUrl.replace(/\/+$/, ''))},
  /** Sentry DSN for SPA error reporting; empty disables it (and keeps the SDK out of the bundle). */
  sentryDsn: ${q(settings.sentryDsn)},
  /** UI language for users who have not picked one (\`en\` or \`it\`). */
  defaultLanguage: ${q(settings.defaultLanguage)},
  supabase: {
    url: ${q(settings.supabaseUrl.replace(/\/+$/, ''))},
    publishableKey: ${q(settings.publishableKey)},
  },
};
`,
);
console.log(`write-env: wrote ${file}`);
